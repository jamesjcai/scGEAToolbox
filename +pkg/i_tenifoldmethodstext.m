function [paragraph, refkeys] = i_tenifoldmethodstext(method, options)
%I_TENIFOLDMETHODSTEXT Methods text for scTenifoldNet, scTenifoldKnk and scTenifoldXct.
%
%   [paragraph, refkeys] = pkg.i_tenifoldmethodstext(method, Name=Value)
%
%   METHOD is "net" (TEN.SCTENIFOLDNET), "knk" (TEN.SCTENIFOLDKNK and its
%   lite and existing-network variants), "xct" (one-sample scTenifoldXct)
%   or "xct2" (two-sample scTenifoldXct). Each paragraph describes the
%   toolbox's default variant of the method, with the settings the entry
%   point passed.
%
%   NAME-VALUE ARGUMENTS
%     Groups       the two groups (net), cell types (xct, xct2: sender
%                  then receiver), or samples (xct2, as Samples)
%     Samples      the two samples of xct2
%     N1, N2       cells in each group, cell type or sample
%     NumCells     cells used (knk)
%     NumSubsamples, SubsampleSize   the network ensemble (net, knk)
%     Gene         the knocked-out gene (knk)
%     Network      "ensemble" (default), "single" (the lite variant) or
%                  "existing" (a network supplied by the user) (knk)
%     Path         "nn", "spectral" (default), "reference" or "python" (xct,
%                  xct2): GUI.CALLBACK_SCTENIFOLDXCT's four implementations
%     W12Mode      "lr" (default) or "outer" (xct, xct2)
%     TwoSided     both directions were tested (xct, xct2)
%     NullControl  the shuffled-network control was run (xct)
%     Control      its diagnostics, one struct per direction: the S output
%                  of TEN.XCTNULLCONTROL (TEN.XCT2NULLCONTROL for xct2)
%                  plus fields Source and Target, and for xct2 optionally
%                  SplitCounts and CalibratedP from
%                  TEN.XCT2SPLITCALIBRATION. Given, the paragraph reports
%                  the verdict, so it cannot be pasted without it
%     NumSignificant  results with adjusted P < 0.05 (net, knk, xct2) or
%                  P < 0.05 (xct); NaN leaves it out
%     NumCandidates  ligand-receptor candidate pairs tested (xct, xct2),
%                  so the count reads "X of Y"; under the default "lr"
%                  linking X is often all of Y, and the text should show it
%
%   See also TEN.SCTENIFOLDNET, TEN.SCTENIFOLDKNK, TEN.SCTENIFOLDXCT,
%   TEN.SCTENIFOLDXCT2, PKG.I_METHODSREPORT.

arguments
    method (1,1) string {mustBeMember(method, ["net", "knk", "xct", "xct2"])}
    options.Groups (1,:) string = ["group 1", "group 2"]
    options.Samples (1,:) string = ["sample 1", "sample 2"]
    options.N1 (1,1) double = NaN
    options.N2 (1,1) double = NaN
    options.NumCells (1,1) double = NaN
    options.NumSubsamples (1,1) double = 10
    options.SubsampleSize (1,1) double = 500
    options.Gene (1,1) string = ""
    options.Network (1,1) string {mustBeMember(options.Network, ["ensemble", "single", "existing"])} = "ensemble"
    options.Path (1,1) string {mustBeMember(options.Path, ["nn", "spectral", "reference", "python"])} = "spectral"
    options.W12Mode (1,1) string {mustBeMember(options.W12Mode, ["lr", "outer"])} = "lr"
    options.TwoSided (1,1) logical = false
    options.NullControl (1,1) logical = false
    options.Control struct = struct([])
    options.NumSignificant (1,1) double = NaN
    options.NumCandidates (1,1) double = NaN
end

num = @pkg.i_thousands;
quoted = @(s, n) """" + s + """" + i_cells(n);
lognorm = "library-size-normalized (10,000 counts per cell) and " + ...
    "log(x + 1)-transformed";
ensemble = sprintf("%s subsamples of %s cells were drawn with replacement; " + ...
    "on each, a principal-component regression network was built (each " + ...
    "gene regressed on the first 3 principal components of the other " + ...
    "genes), scaled to its largest absolute weight and filtered to the top " + ...
    "5%% of edges by absolute weight. The %s networks were denoised by " + ...
    "CANDECOMP/PARAFAC tensor decomposition (rank %s) and averaged", ...
    num(options.NumSubsamples), num(options.SubsampleSize), ...
    num(options.NumSubsamples), num(options.NumSubsamples));

switch method
    case "net"
        refkeys = ["osorio2020", "benjamini1995", "cai2020"];
        paragraph = "Gene regulatory networks of " + ...
            quoted(options.Groups(1), options.N1) + " and " + ...
            quoted(options.Groups(2), options.N2) + " were constructed and " + ...
            "compared with scTenifoldNet (Osorio et al., 2020), as " + ...
            "implemented in scGEAToolbox. Ribosomal genes were removed and " + ...
            "expression was " + lognorm + ". For each group, " + ensemble + ...
            ", and the result was symmetrized. The two networks were aligned " + ...
            "by manifold alignment in 30 dimensions (normalized graph " + ...
            "Laplacian). Each gene's squared distance between its two " + ...
            "aligned positions, divided by the mean over all genes, was " + ...
            "tested against a chi-square distribution with 1 degree of " + ...
            "freedom, and P values were adjusted by the Benjamini–Hochberg " + ...
            "procedure (Benjamini and Hochberg, 1995)";
        paragraph = paragraph + i_count(options.NumSignificant, ...
            "genes were differentially regulated at adjusted P < 0.05") + ".";

    case "knk"
        refkeys = ["osorio2022", "benjamini1995", "cai2020"];
        gene = options.Gene;
        if strlength(gene) == 0, gene = "the target gene"; end
        switch options.Network
            case "ensemble"
                net = "A wild-type gene regulatory network was built as in " + ...
                    "scTenifoldNet (Osorio et al., 2020) from" + i_of(options.NumCells) + ...
                    " cells. Expression was " + lognorm + ". Then " + ensemble + ".";
                refkeys = [refkeys, "osorio2020"];
            case "single"
                net = "A wild-type gene regulatory network was built from" + ...
                    i_of(options.NumCells) + " cells as a single principal-" + ...
                    "component regression network (each gene regressed on " + ...
                    "the first 3 principal components of the other genes) of " + ...
                    lognorm + " expression, without subsampling, edge " + ...
                    "filtering or tensor denoising.";
            otherwise
                net = "The analysis used a gene regulatory network supplied " + ...
                    "by the user rather than one constructed in this run.";
        end
        paragraph = "A virtual knockout of " + gene + " was performed with " + ...
            "scTenifoldKnk (Osorio et al., 2022), as implemented in " + ...
            "scGEAToolbox. " + net + " The knockout network was obtained by " + ...
            "removing all outgoing edges of " + gene + ". The wild-type and " + ...
            "knockout networks were symmetrized and aligned by manifold " + ...
            "alignment in 2 dimensions (normalized graph Laplacian). Each " + ...
            "gene's squared distance between its two aligned positions, " + ...
            "divided by the mean over all genes, was tested against a " + ...
            "chi-square distribution with 1 degree of freedom, and P values " + ...
            "were adjusted by the Benjamini–Hochberg procedure (Benjamini " + ...
            "and Hochberg, 1995)";
        paragraph = paragraph + i_count(options.NumSignificant, ...
            "genes other than " + gene + " were perturbed at adjusted P < 0.05") + ".";

    otherwise   % xct, xct2
        refkeys = ["yang2023", "cai2020"];
        sender = options.Groups(1);
        receiver = options.Groups(2);
        switch options.Path
            case {"nn", "reference"}
                grn = "a principal-component regression network on 5 " + ...
                    "principal components, without edge filtering, as in the " + ...
                    "published implementation";
            otherwise
                grn = "a principal-component regression network on 3 " + ...
                    "principal components, scaled to its largest absolute " + ...
                    "weight and filtered to the top 25% of edges by absolute " + ...
                    "weight";
        end
        % The pair list is assets/Ligand_Receptor, from Ramilowski et al.
        % (2015); TEN.I_XCTCORE loads it.
        if options.W12Mode == "lr"
            link = "linked through the cognate ligand–receptor pairs of " + ...
                "Ramilowski et al. (2015) (weight 1 per pair)";
        else
            link = "linked through the ligand–receptor pairs of Ramilowski " + ...
                "et al. (2015), weighted by the outer product of the two " + ...
                "cell types' expression";
        end
        if options.Path ~= "python"
            refkeys = [refkeys, "ramilowski2015"];
        end
        if options.Path == "nn"
            embed = "genes were embedded in 3 dimensions by neural networks " + ...
                "trained with Adam (1,000 steps, learning rate 0.01) to place " + ...
                "corresponding genes close while preserving each network's " + ...
                "structure";
        else
            embed = "genes were embedded in 3 dimensions by the eigenvectors " + ...
                "of the graph Laplacian of the joined network";
        end
        if options.TwoSided
            dirs = " in both directions";
        else
            dirs = "";
        end

        if method == "xct"
            paragraph = "Ligand–receptor-mediated interactions from " + ...
                quoted(sender, options.N1) + " to " + quoted(receiver, options.N2) + ...
                dirs + " were predicted with scTenifoldXct (Yang et al., 2023)";
            if options.Path == "python"
                paragraph = paragraph + ", using the authors' Python package " + ...
                    "with networks built in scGEAToolbox (" + grn + ") from " + ...
                    "expression scaled to the median library size and log(x " + ...
                    "+ 1)-transformed.";
            else
                paragraph = paragraph + ", as implemented in scGEAToolbox. " + ...
                    "Expression of each cell type was scaled to the median " + ...
                    "library size and log(x + 1)-transformed, and a gene " + ...
                    "network was built for each cell type as " + grn + ". The " + ...
                    "two networks were " + link + ", and " + embed + ". Each " + ...
                    "candidate pair was scored by the Euclidean distance " + ...
                    "between the ligand in the sender and the receptor in the " + ...
                    "receiver, and its P value was the percentile of that " + ...
                    "distance among all non-candidate gene pairs, without " + ...
                    "multiple-testing correction.";
            end
            paragraph = paragraph + i_count(options.NumSignificant, ...
                i_ofcandidates(options.NumCandidates) + "had P < 0.05", true);
            if ~isempty(options.Control)
                paragraph = paragraph + i_controltext(options.Control, false);
            elseif options.NullControl
                paragraph = paragraph + " The dependence of the result on " + ...
                    "the networks was checked by repeating the analysis " + ...
                    "with the networks' gene labels shuffled 20 times.";
            end
        else
            paragraph = "Changes in ligand–receptor-mediated interactions from " + ...
                """" + sender + """ to """ + receiver + """" + dirs + ...
                " between " + quoted(options.Samples(1), options.N1) + ...
                " and " + quoted(options.Samples(2), options.N2) + ...
                " were assessed with the two-sample mode of scTenifoldXct " + ...
                "(Yang et al., 2023)";
            if options.Path == "python"
                paragraph = paragraph + ", using the authors' Python package " + ...
                    "with networks built in scGEAToolbox.";
            else
                paragraph = paragraph + ", as implemented in scGEAToolbox. " + ...
                    "For each sample, a gene network was built for each cell " + ...
                    "type as " + grn + "; the two networks were " + link + ...
                    ", and " + embed + ". For every " + ...
                    "gene pair, the squared difference between its distances " + ...
                    "in the two samples, divided by the mean over all pairs, " + ...
                    "was tested against a chi-square distribution with 1 " + ...
                    "degree of freedom, and P values were adjusted by the " + ...
                    "Benjamini–Hochberg procedure (Benjamini and Hochberg, " + ...
                    "1995) over all gene pairs; ligand–receptor pairs were " + ...
                    "then reported.";
                refkeys = [refkeys, "benjamini1995"];
            end
            paragraph = paragraph + i_count(options.NumSignificant, ...
                i_ofcandidates(options.NumCandidates) + ...
                "changed at adjusted P < 0.05", true);
            if ~isempty(options.Control)
                paragraph = paragraph + i_controltext(options.Control, true);
            elseif options.NullControl
                paragraph = paragraph + " The dependence of the result on " + ...
                    "the networks was checked by repeating the analysis " + ...
                    "with the networks' gene labels shuffled 20 times.";
            end
        end
end
end


function s = i_cells(n)
if isnan(n), s = ""; else, s = " (" + pkg.i_thousands(n) + " cells)"; end
end


function s = i_controltext(C, twosample)
% The shuffled-network control's outcome, one sentence per direction, from
% TEN.XCTNULLCONTROL's (or, TWOSAMPLE, TEN.XCT2NULLCONTROL's) diagnostics.
% Their verdict rule: insensitive when the shuffles keep both the ranking
% (median Spearman >= 0.9) and the calls (median Jaccard >= 0.8).
num = @pkg.i_thousands;
if twosample
    shuffled = "each cell type's network gene labels shuffled, with the " + ...
        "same shuffle in both samples";
    measure = "changes between samples";
    called = "pairs called at adjusted P < 0.05";
    beat = "changed more than in their shuffles";
else
    shuffled = "each network's gene labels shuffled";
    measure = "distances";
    called = "pairs called at P < 0.05";
    beat = "were placed closer than in their shuffles";
end
s = sprintf(" The dependence of the result on the gene networks was " + ...
    "tested by repeating the analysis %s times with ", num(C(1).NumShuffles)) + ...
    shuffled + ".";
for k = 1:numel(C)
    c = C(k);
    % For two samples the verdict is about the ranking only: random splits
    % of one sample, where nothing differs, are rated sensitive too.
    if twosample
        subject = "the ranking of changes";
    else
        subject = "the result";
    end
    if c.NetworkSensitive
        verdict = subject + " depended on the networks";
    else
        verdict = subject + " did not depend on the networks";
    end
    % Two empty call sets overlap 100% by convention, which would read as
    % agreement; with nothing called in the real run, say that instead.
    if isfield(c, 'NumSigReal') && c.NumSigReal == 0
        calls = "no pair was called at " + extractAfter(called, "called at ") + " in the real run";
    else
        calls = sprintf("the %s overlapped %s%% (median Jaccard)", called, ...
            string(round(100*c.MedianSigJaccard)));
    end
    s = s + sprintf(" For %s to %s, %s: the candidates' " + ...
        "%s correlated %.3f with those under the shuffles (median " + ...
        "Spearman) and %s. %s of %s pairs %s at empirical P ≤ 0.05", ...
        """" + string(c.Source) + """", """" + string(c.Target) + """", ...
        verdict, measure, c.MedianRho, calls, num(c.NumEmpPBelow05), ...
        num(c.NumCandidates), beat);
    if ~twosample
        s = s + sprintf(", against about %s expected by chance.", ...
            string(round(c.NumExpectedByChance)));
    elseif isfield(c, 'SplitCounts') && ~isempty(c.SplitCounts)
        % TEN.XCT2SPLITCALIBRATION: the count against random splits of the
        % same cells, the null an empirical P count needs for two samples.
        s = s + sprintf(". In %s random splits of the same cells into two " + ...
            "pseudo-samples of the original sizes, where nothing differs, " + ...
            "%s pairs did so (mean %.1f); the real count was matched or " + ...
            "exceeded in %s of them (calibrated P = %.2g).", ...
            num(numel(c.SplitCounts)), strjoin(string(c.SplitCounts), ", "), ...
            mean(c.SplitCounts), num(nnz(c.SplitCounts >= c.NumEmpPBelow05)), ...
            c.CalibratedP);
    else
        s = s + ". Empirical P is not calibrated for a change between " + ...
            "samples: random splits of a single sample give more such pairs " + ...
            "than shuffling predicts, so this count was not taken as " + ...
            "evidence of a difference between the samples.";
    end
end
end


function s = i_ofcandidates(n)
% "of 494 candidate ligand–receptor pairs " or "ligand–receptor pairs ".
if isnan(n)
    s = "ligand–receptor pairs ";
else
    s = "of " + pkg.i_thousands(n) + " candidate ligand–receptor pairs ";
end
end


function s = i_of(n)
if isnan(n), s = " all"; else, s = " " + pkg.i_thousands(n); end
end


function s = i_count(n, what, sentence)
% "; 120 genes were ..." appended to a clause, or " 120 pairs ..." as a
% sentence of its own when SENTENCE.
if nargin < 3, sentence = false; end
if isnan(n)
    s = "";
    if sentence, s = ""; end
    return
end
if sentence
    s = " " + pkg.i_thousands(n) + " " + what + ".";
else
    s = "; " + pkg.i_thousands(n) + " " + what;
end
end
